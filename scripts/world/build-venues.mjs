// Build src/lib/venues/<slug>.ts for each reconstructed world hospital sheet.
// World equivalent of scripts/maps/build-venues.mjs — identical placement
// logic (waypoints land on their labels because both come from the same
// coordinate extraction), just reading data/world/mapped-sites.json. Writes
// into the same src/lib/venues/ directory as every other venue; slugs are
// globally unique (country-suffixed by draft-sheets.mjs) so there's no
// collision with NHS's own generated sheets.
//
// Run: node scripts/world/build-venues.mjs
import { extractLabels } from "../maps/extract.mjs"
import { readSheets, WORLD_CONFIG } from "../maps/sheets.mjs"
import { writeFileSync } from "fs"

const VENUES = readSheets(WORLD_CONFIG)

const R = 111320 // metres per degree latitude

function slugify(s) {
  return s.toLowerCase().replace(/['’]/g, "").replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "") || "wp"
}
const esc = (s) => s.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, "\\n").replace(/\r/g, "\\r").replace(/\t/g, "\\t")
const r6 = (n) => Number(n.toFixed(6))

async function placeFloor(v, floor, usedIds) {
  const { labels, W, H } = await extractLabels(floor.file, floor.page)
  const [px0, py0, px1, py1] = floor.plan
  const inPlan = labels.filter((l) => l.nx >= px0 && l.nx <= px1 && l.ny >= py0 && l.ny <= py1)

  const [lat0, lng0] = v.center
  const dLng = v.spanM / (R * Math.cos((lat0 * Math.PI) / 180))
  const dLat = (v.spanM * (H / W)) / R
  const pcx = (px0 + px1) / 2, pcy = (py0 + py1) / 2
  const lngW = lng0 - pcx * dLng
  const latN = lat0 + pcy * dLat

  const toLatLng = (nx, ny) => [r6(latN - ny * dLat), r6(lngW + nx * dLng)]

  const wps = inPlan.map((l) => {
    const base = `${slugify(l.text)}-f${floor.floor}`
    const n = usedIds[base] || 0
    usedIds[base] = n + 1
    const id = n === 0 ? base : `${base}-${n + 1}`
    const [lat, lng] = toLatLng(l.nx, l.ny)
    return { id, name: l.text, type: l.type, lat, lng, floor: floor.floor }
  })

  const [bS, bW] = toLatLng(0, 1)
  const [bN, bE] = toLatLng(1, 0)
  return { wps, bounds: [bS, bW, bN, bE] }
}

async function build(v) {
  const [lat0, lng0] = v.center
  const usedIds = {}
  const placed = []
  for (const floor of v.floors) placed.push({ floor, ...(await placeFloor(v, floor, usedIds)) })
  const wps = placed.flatMap((p) => p.wps)

  const L = []
  L.push('import { Venue } from "../types"')
  L.push("")
  L.push(`// ${v.name} — reconstructed from the hospital's own map sheet${v.floors.length > 1 ? "s" : ""}`)
  L.push(`// (${v.floors.map((f) => f.file).join(", ")}).`)
  L.push("// Generated by scripts/world/build-venues.mjs — edit that, not this.")
  L.push("")
  L.push(`export const ${v.slug.toUpperCase().replace(/-/g, "_")}_VENUE: Venue = {`)
  L.push(`  id: "${v.id}",`)
  L.push(`  slug: "${v.slug}",`)
  L.push(`  name: "${esc(v.name)}",`)
  L.push(`  subtitle: "${esc(v.subtitle)}",`)
  L.push('  category: "hospital",')
  L.push(`  center: { lat: ${r6(lat0)}, lng: ${r6(lng0)} },`)
  L.push("  defaultZoom: 17,")
  L.push('  visibility: "public",')
  L.push("  verified: false,")
  L.push(`  accessibility: { stepFreeRoute: true, accessibleToilets: true, notes: "${esc(v.notes)}" },`)
  L.push(`  quickAccess: [${v.quick.map((q) => `"${esc(q)}"`).join(", ")}],`)
  L.push("  floorPlans: [")
  for (const { floor, bounds: [bS, bW, bN, bE] } of placed) {
    L.push(
      `    { id: "${floor.id}", floor: ${floor.floor}, label: "${esc(floor.label)}", ` +
        `imageUrl: "/floorplans/${v.slug}/${floor.image}.svg", bounds: [[${r6(bS)}, ${r6(bW)}], [${r6(bN)}, ${r6(bE)}]] },`
    )
  }
  L.push("  ],")
  L.push("  waypoints: [")
  for (const w of wps) {
    L.push(`    { id: "${w.id}", name: "${esc(w.name)}", type: "${w.type}", coordinates: { lat: ${w.lat}, lng: ${w.lng} }, floor: ${w.floor} },`)
  }
  L.push("  ],")
  L.push("}")
  L.push("")
  writeFileSync(`src/lib/venues/${v.slug}.ts`, L.join("\n"))
  return { slug: v.slug, count: wps.length }
}

for (const v of VENUES) {
  const r = await build(v)
  console.log(`${r.slug}: ${r.count} waypoints`)
}
